import { test, expect } from '@playwright/test';
import { clearFixtures, seedEvents, createFixtureUser, callIdentity, signInFixture, password, fixtureDb } from '../fixtures';
import { emptyDetails } from '../../shared/profile';
import { readingHold, readHelp, reviewRecording } from '../review-recording';

test('recording: shared design system and contextual help walkthrough', async ({ page }) => {
  test.skip(!reviewRecording, 'Only in the explicitly authorized recording window');
  test.setTimeout(240000);
  await clearFixtures(); await seedEvents();
  for (const uid of ['organizer', 'ui-demo-owner', 'ui-demo-peer']) await createFixtureUser(uid);
  const ownerToken = await signInFixture('ui-demo-owner');
  const peerToken = await signInFixture('ui-demo-peer');
  expect((await callIdentity(ownerToken, 'save-profile', { name: 'Synthetic UI Member', ...emptyDetails(), professional: { title: 'Community designer', skills: 'Design' }, communityFields: ['title'], contacts: { contactEmail: 'ui-demo@contact.test' }, connectionFields: ['contactEmail'] })).status).toBe(200);
  expect((await callIdentity(peerToken, 'save-profile', { name: 'Synthetic Connected Member', ...emptyDetails(), contacts: { phone: '+6581234567' }, connectionFields: ['phone'] })).status).toBe(200);
  const request = await callIdentity(ownerToken, 'connections/request', { peerUid: 'ui-demo-peer' });
  expect(request.status).toBe(200);
  expect((await callIdentity(peerToken, 'connections/accept', { peerUid: 'ui-demo-owner', generation: request.data.generation })).status).toBe(200);
  expect((await callIdentity(await signInFixture('organizer'), 'event-roles', { sessionId: 'event-one', memberUid: 'ui-demo-owner', roles: ['mentor'] })).status).toBe(200);

  await page.goto('/account');
  await page.getByLabel('Email', { exact: true }).fill('ui-demo-owner@example.test');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in with email', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your profile', exact: true })).toBeVisible();
  const before = (await fixtureDb.doc('profileDetails/ui-demo-owner').get()).data();
  let saves = 0;
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/api/identity/save-profile')) saves += 1; });
  await readingHold(page, 'desktop-profile-foundations');
  await readHelp(page, 'Profile visibility'); await readHelp(page, 'Profile photo'); await readHelp(page, 'Skills');
  await page.setViewportSize({ width: 390, height: 760 });
  await readHelp(page, 'Mobile number'); await readHelp(page, 'Contact sharing');
  await readHelp(page, 'Telegram username or link'); await readHelp(page, 'WhatsApp number');
  await expect(page.getByLabel('Share Contact email with all approved connections', { exact: true })).toBeChecked();
  await expect(page.getByLabel('Use my mobile number for WhatsApp', { exact: true })).not.toBeChecked();
  expect(saves).toBe(0); expect((await fixtureDb.doc('profileDetails/ui-demo-owner').get()).data()).toEqual(before);
  await page.goto('/connections');
  await expect(page.getByRole('region', { name: 'Accepted connections', exact: true })).toContainText('Synthetic Connected Member');
  await readingHold(page, 'populated-connections'); await readHelp(page, 'Connections and contact sharing');
  await page.goto('/badge'); await page.setViewportSize({ width: 320, height: 740 });
  await expect(page.getByRole('article', { name: 'Personal event badge', exact: true })).toBeVisible();
  await readHelp(page, 'Badge profile visibility'); await readingHold(page, 'light-badge-primary-qr');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.goto('/account'); await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Sign in to #HACK Live', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1100, height: 760 }); await page.goto('/admin/event-one');
  await page.getByLabel('Email', { exact: true }).fill('organizer@example.test');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in with email', exact: true }).click();
  await page.getByRole('button', { name: 'Public invitation', exact: true }).click();
  await readHelp(page, 'Event timezone (IANA)');
  await expect(page.getByRole('button', { name: 'Publish event details', exact: true })).toBeVisible();
  await readingHold(page, 'admin-primary-actions');
});
